function venuesForCountry(country, coordinates) {
  return coordinates.trim().split(/\s+/).map((value, index) => ({
    id: `lego-${country.toLowerCase()}-${index + 1}`,
    name: `LEGO Store ${country} ${String(index + 1).padStart(3, "0")}`,
    coordinates: value,
    group: country
  }));
}

